"""Plot the reviewer-response chain MRF figures from freshly summarized runs."""

import argparse
import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

PANELS = {
    1: (("tv1", "TV-1D"), ("tv2", "TV-2D pairs"),
        ("llgap", "LL gap"), ("energy", "Energy (×1000)"),
        ("sw", "SW (×100)")),
    2: (("tv1", "TV-1D"), ("tv2", "TV-2D pairs"),
        ("joint_tv", "Joint TV"), ("llgap", "LL gap")),
}
SAMPLE_SIZES = (500, 1000, 2000, 4000, 8000, 16000)


def load_summary(path: Path, figure: int) -> dict[tuple[int, str, str], tuple[float, float]]:
    expected_table = 1 if figure == 1 else 3
    cells = {}
    with path.open(newline="") as stream:
        for row in csv.DictReader(stream):
            if int(row["table"]) != expected_table:
                raise ValueError(f"{path} contains the wrong response table")
            key = (int(row["n"]), row["method"], row["metric"])
            if key in cells:
                raise ValueError(f"duplicate summary cell: {key}")
            cells[key] = (float(row["mean"]), float(row["sample_sd"]))
    return cells


def render(figure: int, input_path: Path, output: Path) -> None:
    cells = load_summary(input_path, figure)
    panels = PANELS[figure]
    fig, axes = plt.subplots(1, len(panels), figsize=(3.8 * len(panels), 3.6),
                             constrained_layout=True)
    for ax, (metric, title) in zip(axes, panels):
        for method, color, marker in (("cindes", "#145a8d", "o"),
                                      ("dsm", "#b54e36", "s")):
            key_metric = ("joint_tv_lower_bound" if metric == "joint_tv" and method == "dsm"
                          else metric)
            try:
                points = [cells[n, method, key_metric] for n in SAMPLE_SIZES]
            except KeyError as error:
                raise ValueError(f"missing {error} in {input_path}") from error
            means = np.array([point[0] for point in points])
            deviations = np.array([point[1] for point in points])
            label = "DSM lower bound" if key_metric == "joint_tv_lower_bound" else method.upper()
            ax.errorbar(SAMPLE_SIZES, means, yerr=deviations, color=color, marker=marker,
                        linewidth=1.5, capsize=2, label=label)
        ax.set_xscale("log", base=2)
        ax.set_xticks(SAMPLE_SIZES, ["500", "1k", "2k", "4k", "8k", "16k"], rotation=45)
        ax.set_title(title)
        ax.set_xlabel("Training sample size n")
        ax.grid(alpha=0.2)
        ax.legend(fontsize=8)
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output)
    plt.close(fig)
    print(f"Wrote response Figure {figure} to {output}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--figure", type=int, choices=(1, 2), required=True)
    parser.add_argument("--input", type=Path, required=True,
                        help="CSV generated by response/summarize.py")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    render(args.figure, args.input, args.output)


if __name__ == "__main__":
    main()
